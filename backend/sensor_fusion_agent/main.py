async def get_analytics(city: str = "Hyderabad"):
    """
    Get historical AQI trends, future predictions, and AccuWeather insights.
    """
    import ml_engine
    import accuweather_client
    import ml_engine_lgbm

    print(f"Analytics requested for {city}")
    
    # 1. Get Prediction Seed
    live_aqi = 100 
    current_pm25 = 45.0 # Default fallback
    
    # 2. Fetch Live Data (Sensor Fusion + AccuWeather)
    accu_data = None
    async with httpx.AsyncClient() as client:
        try:
            coords = await fetch_coordinates(client, city)
            aq_data = await fetch_air_quality(client, coords["lat"], coords["lon"])
            
            # Map OpenWeather Index to AQI for seeding the model
            # Use calculated AQI directly
            live_aqi = aq_data["aqi_index"]
            if "pm2_5" in aq_data["components"]:
                current_pm25 = aq_data["components"]["pm2_5"]
            
            # ACCUWEATHER INTEGRATION
            try:
                print("Fetching AccuWeather data...")
                accu_full = await accuweather_client.fetch_accuweather_data(client, city)
                if accu_full:
                    accu_data = accu_full.get("current") 
            except Exception as e:
                print(f"AccuWeather fetch failed: {e}")

        except Exception as e:
             print(f"Live data fetch error: {e}")

    # 3. Generate ML Predictions (Prefer LightGBM)
    predictions = []
    model_source = "Random Forest (Fallback)"
    
    try:
        # Try LightGBM first
        pm25_preds = ml_engine_lgbm.predict_pm25_next_days(state="Telangana", city=city, current_pm25=current_pm25, days=4)
        # Convert PM2.5 to AQI (Approximate for display)
        # Ind-AQI sub-index for PM2.5: 
        # 0-30->0-50, 30-60->50-100, 60-90->100-200, 90-120->200-300, 120-250->300-400
        for p in pm25_preds:
            pm = p["predicted_pm25"]
            aqi = pm * 2 # Roughly 2x for simplistic conversion in moderate range
            if pm > 60: aqi = 100 + (pm - 60) * 3.3
            if pm > 90: aqi = 200 + (pm - 90) * 3.3
            if pm > 120: aqi = 300 + (pm - 120) * 0.7
            
            predictions.append({
                "date": p["date"],
                "predicted_aqi": int(aqi),
                "predicted_pm25": pm
            })
        model_source = "LightGBM (City-Aware)"
    except Exception as e:
        print(f"LightGBM failed, falling back to RF: {e}")
        predictions = ml_engine.predict_days(live_aqi, days=4)

    return {
        "city": city,
        "current_aqi_estimate": live_aqi,
        "forecast": predictions,
        "status": "generated",
        "model_source": model_source
    }

@app.get("/hotspots", response_model=List[FusedSensorSnapshot])
async def get_live_hotspots():
    """
    Returns live fused data for major Indian cities.
    """
    # Updated list of 7 major cities correctly
    cities = ["New Delhi", "Mumbai", "Hyderabad", "Bangalore", "Chennai", "Kolkata", "Ayodhya"]
    
    async with httpx.AsyncClient() as client:
        # 1. Geocode all cities in parallel
        coord_tasks = [fetch_coordinates(client, city) for city in cities]
        coords_results = await asyncio.gather(*coord_tasks, return_exceptions=True)
        
        valid_coords = []
        for res in coords_results:
            if not isinstance(res, Exception):
                valid_coords.append(res)
        
        # 2. Fetch Data for all cities in parallel
        # We need to replicate the fusion logic here efficiently
        fusion_tasks = []
        
        async def fetch_city_data(c):
            try:
                lat, lon = c["lat"], c["lon"]
                aq_data, w_data = await asyncio.gather(
                    fetch_air_quality(client, lat, lon),
                    fetch_weather(client, lat, lon),
                )
                ts = max(aq_data["dt"], w_data["dt"])
                dispersion = compute_dispersion_score(
                    aqi_index=aq_data["aqi_index"],
                    wind_speed=w_data["wind_speed"],
                    clouds=w_data["clouds"],
                )
                health_risk = aqi_to_category(aq_data["aqi_index"])
                insight = generate_agent_insight(health_risk, w_data["wind_speed"], aq_data["components"]["pm2_5"], aq_data["components"]["pm10"], aq_data["aqi_index"])
                
                # Append City Name to insight for context
                insight = f"{c['name']}: {insight}" 
                
                snapshot = FusedSensorSnapshot(
                    lat=lat,
                    lon=lon,
                    timestamp_utc=datetime.fromtimestamp(ts),
                    air_quality=AirQuality(
                        aqi_index=aq_data["aqi_index"],
                        aqi_category=health_risk,
                        components=PollutantComponents(**aq_data["components"]),
                    ),
                    weather=Weather(**{k: v for k, v in w_data.items() if k != "dt"}),
                    dispersion_score=dispersion,
                    health_risk_level=health_risk,
                    agent_insight=insight
                )
                return snapshot
            except Exception as e:
                print(f"Error fetching hotspot for {c['name']}: {e}")
                return None

        for c in valid_coords:
            fusion_tasks.append(fetch_city_data(c))
            
        snapshots = await asyncio.gather(*fusion_tasks)
        valid_snapshots = [s for s in snapshots if s is not None]

        # Log to cache
        if valid_snapshots:
            # We log the whole batch or individual items? Let's log brief summary
            await save_to_json_cache({
                "type": "hotspots_update",
                "count": len(valid_snapshots),
                "cities": [s.agent_insight.split(':')[0] for s in valid_snapshots], # extracted name from insight hack
                "data_sample": json.loads(valid_snapshots[0].json()) if valid_snapshots else None
            })

        return valid_snapshots

