def compute_dispersion_score(aqi_index: int, wind_speed: float, clouds: int) -> float:
    base = max(0.0, 6 - aqi_index)
    wind_factor = min(wind_speed / 5.0, 2.0)
    cloud_factor = max(0.5, 1.5 - clouds / 100.0)
    return round(base * wind_factor * cloud_factor, 2)


