@app.get("/news", response_model=dict)
async def get_city_news(city: str = Query(..., min_length=1)):
    """
    Fetches top 3 pollution-related news articles for the city.
    Uses Google News RSS (Public Feed) to avoid API keys.
    """
    import xml.etree.ElementTree as ET
    from email.utils import parsedate_to_datetime

    rss_url = f"https://news.google.com/rss/search?q={city}+air+pollution+when:7d&hl=en-US&gl=US&ceid=US:en"
    
    articles = []
    print(f"Fetching news for {city} from {rss_url}")
    
    async with httpx.AsyncClient() as client:
        try:
            response = await client.get(rss_url, timeout=10.0)
            if response.status_code == 200:
                root = ET.fromstring(response.content)
                # Parse headlines
                count = 0
                for item in root.findall(".//item"):
                    if count >= 3: break
                    
                    try:
                        title = item.find("title").text
                        link = item.find("link").text
                        pub_date = item.find("pubDate").text
                        source = item.find("source").text if item.find("source") is not None else "Google News"
                        
                        # Formatting relative time
                        try:
                            dt = parsedate_to_datetime(pub_date)
                            now = datetime.now(dt.tzinfo)
                            diff = now - dt
                            if diff.days > 0:
                                time_str = f"{diff.days}d ago"
                            elif diff.seconds > 3600:
                                time_str = f"{diff.seconds // 3600}h ago"
                            else:
                                time_str = f"{diff.seconds // 60}m ago"
                        except:
                            time_str = "Recently"

                        articles.append(NewsArticle(
                            title=title,
                            url=link,
                            source=source,
                            published_at=time_str
                        ))
                        count += 1
                    except Exception as parse_err:
                        print(f"Error parsing article: {parse_err}")
                        continue
        except Exception as e:
            print(f"News fetch error: {e}")
            # Don't fail the whole app, just return empty list
            pass
            
    return {"city": city, "articles": articles}


