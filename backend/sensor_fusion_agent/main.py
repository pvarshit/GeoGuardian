@app.get("/explorer/history")
async def get_explorer_history(city: str = "Hyderabad"):
    """
    Aggregates historical data from local Excel files for the dashboard.
    Returns trends, monthly averages, and summary stats.
    """
    try:
        import pandas as pd
        import glob
        
        data_dir = "data"
        # Find all excel files matching the city (case insensitive)
        # We list all xlsx files and filter in python to be safe against case sensitivity
        all_files = glob.glob(f"{data_dir}/*.xlsx")
        files = [f for f in all_files if city.lower() in f.lower()]
        
        if not files:
            # Fallback for debugging: print what we found
            print(f"No files found for {city} in {data_dir}. Available: {all_files}")
            # Optional: Fallback to dummy data only if STRICTLY needed, or just return empty
            # files = glob.glob(f"{data_dir}/dummy_aqi.xlsx")
            
        if not files:
            return {"error": f"No historical data found for {city}"}

        dfs = []
        for f in files:
            try:
                df = pd.read_excel(f)
                dfs.append(df)
            except Exception as e:
                print(f"Error reading {f}: {e}")
                continue
        
        if not dfs:
            return {"error": "Could not read data files"}
            
        full_df = pd.concat(dfs, ignore_index=True)
        
        # Normalize columns
        # Map various possible names to standard keys
        col_map = {
            'Temp (degree C)': 'temp',
            'AT (degree C)': 'temp',
            'temperature': 'temp',
            'RH (%)': 'humidity',
            'humidity': 'humidity',
            'WS (m/s)': 'wind_speed',
            'wind_speed': 'wind_speed'
        }
        full_df = full_df.rename(columns=col_map)
        
        # Ensure Date column exists and is datetime
        date_col = None
        for col in full_df.columns:
            if "date" in col.lower():
                date_col = col
                break
        
        if not date_col:
            print(f"Columns found: {full_df.columns}")
            return {"error": "Date column missing in data"}
            
        full_df[date_col] = pd.to_datetime(full_df[date_col])
        full_df = full_df.sort_values(date_col)
        
        # 1. Summary Stats
        summary = {
            "total_records": int(len(full_df)),
            "avg_aqi": int(full_df['AQI'].mean()) if 'AQI' in full_df else 0,
            "avg_pm25": float(full_df['PM2.5'].mean()) if 'PM2.5' in full_df else 0,
            "max_aqi": int(full_df['AQI'].max()) if 'AQI' in full_df else 0
        }
        
        # 2. Trend Data (Daily)
        # Resample to daily if dense, or just take the records
        trend_df = full_df.copy()
        trend_df['date_str'] = trend_df[date_col].dt.strftime('%Y-%m-%d')
        trend_data = trend_df.to_dict(orient='records')
        # Clean keys for frontend
        clean_trend = []
        for item in trend_data:
            # map columns if they exist (handling variations simplistically)
            # EDA code showed: 'Temp (degree C)', 'RH (%)', 'WS (m/s)'
            row = {}
            row["date"] = item[date_col].strftime('%Y-%m-%d')
            row["aqi"] = item.get('AQI', 0)
            row["pm25"] = item.get('PM2.5', 0)
            
            # Weather metrics (using normalized names)
            row["temp"] = item.get('temp', 0)
            row["humidity"] = item.get('humidity', 0)
            row["wind_speed"] = item.get('wind_speed', 0)
            
            clean_trend.append(row)
            
        # 3. Monthly Distribution (Boxplot-ish stats)
        full_df['Month'] = full_df[date_col].dt.month_name().str[:3] # Jan, Feb...
        monthly_stats = []
        months_order = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
        
        for month in months_order:
            m_df = full_df[full_df['Month'] == month]
            if not m_df.empty:
                monthly_stats.append({
                    "name": month,
                    "avg_pm25": float(m_df['PM2.5'].mean()),
                    "max_pm25": float(m_df['PM2.5'].max()),
                    "min_pm25": float(m_df['PM2.5'].min())
                })
        
        return {
            "city": city,
            "summary": summary,
            "trend": clean_trend,
            "monthly": monthly_stats
        }

    except Exception as e:
        print(f"Explorer error: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))


