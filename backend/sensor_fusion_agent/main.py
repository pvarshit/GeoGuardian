# ------------- Helper functions -------------

def calculate_sub_index(concentration: float, breakpoints: List[tuple]) -> int:
    """Calculates sub-index for a single pollutant based on breakpoints."""
    for (low_c, high_c, low_i, high_i) in breakpoints:
        if low_c <= concentration <= high_c:
            return int(low_i + (high_i - low_i) / (high_c - low_c) * (concentration - low_c))
    return 500 # Cap at 500 if exceeds

def calculate_ind_aqi(pm25: float, pm10: float) -> int:
    """Calculates Indian AQI (0-500) based on PM2.5 and PM10."""
    # Breakpoints (Conc Low, Conc High, AQI Low, AQI High)
    pm25_bp = [
        (0, 30, 0, 50), (30, 60, 51, 100), (60, 90, 101, 200),
        (90, 120, 201, 300), (120, 250, 301, 400), (250, 1000, 401, 500)
    ]
    pm10_bp = [
        (0, 50, 0, 50), (50, 100, 51, 100), (100, 250, 101, 200),
        (250, 350, 201, 300), (350, 430, 301, 400), (430, 1000, 401, 500)
    ]
    
    val25 = calculate_sub_index(pm25, pm25_bp)
    val10 = calculate_sub_index(pm10, pm10_bp)
    
    return max(val25, val10)

def aqi_to_category(aqi: int) -> AQICategory:
    # Standard AQI Scale 0-500
    if aqi <= 50: return AQICategory.good
    if aqi <= 100: return AQICategory.fair # Satisfactory
    if aqi <= 200: return AQICategory.moderate
    if aqi <= 300: return AQICategory.poor
    if aqi <= 400: return AQICategory.very_poor
    return AQICategory.severe

def generate_agent_insight(aqi_cat: AQICategory, wind_speed: float, pm25: float, pm10: float, aqi_score: int) -> str:
    """Generates a dynamic text insight based on fusion of signals."""
    insight = f"Air quality is {aqi_cat.value} (AQI: {aqi_score} | PM2.5: {pm25:.1f} | PM10: {pm10:.1f})."
    if aqi_cat in [AQICategory.poor, AQICategory.very_poor, AQICategory.severe]:
        insight += " Hazardous levels."
    elif aqi_cat == AQICategory.moderate:
        insight += " Acceptable."
    else:
        insight += " Good air."
        
    if wind_speed > 20:
        insight += " High winds active."
    elif wind_speed < 5 and pm25 > 50:
        insight += " Stagnant air."
        
    return insight

async def save_to_json_cache(data: dict, filename: str = "sensor_data_log.json"):
    """
    Appends the given data to a JSON file, ensuring it remains a valid JSON array.
    """
    try:
        # Add timestamp if missing
        if "timestamp_logged" not in data:
            data["timestamp_logged"] = datetime.now().isoformat()
        
        # Read existing file to check if it's empty or has data
        file_exists = os.path.exists(filename)
        mode = 'r+' if file_exists else 'w'
        
        if not file_exists:
            # Create new array
            async with aiofiles.open(filename, mode='w') as f:
                await f.write(json.dumps([data], indent=2))
        else:
            # Append seamlessly to the array
            # This is not efficient for massive files but fine for this demo/log size
            try:
                async with aiofiles.open(filename, mode='r') as f:
                    content = await f.read()
                    existing_data = json.loads(content) if content else []
                    if not isinstance(existing_data, list): existing_data = [existing_data]
            except Exception:
                existing_data = [] # Corrupt file reset
            
            existing_data.append(data)
            
            async with aiofiles.open(filename, mode='w') as f:
                await f.write(json.dumps(existing_data, indent=2))
                
    except Exception as e:
        print(f"Failed to log data to cache: {e}")
        import traceback
        traceback.print_exc()

async def fetch_air_quality(client: httpx.AsyncClient, lat: float, lon: float):
    key = os.getenv("OPENWEATHER_API_KEY")
    if not key:
        return {
            "aqi_index": 150,
            "components": {"co": 250, "no": 0.5, "no2": 10, "o3": 60, "so2": 15, "pm2_5": 45, "pm10": 80, "nh3": 2},
            "dt": int(datetime.utcnow().timestamp())
        }

    url = f"{OPENWEATHER_BASE}/data/2.5/air_pollution"
    params = {"lat": lat, "lon": lon, "appid": key}
    r = await client.get(url, params=params, timeout=10)
    if r.status_code != 200:
         # Fallback mock on error
        print(f"API Error: {r.text}")
        return {
            "aqi_index": 150,
            "components": {"co": 250, "no": 0.5, "no2": 10, "o3": 60, "so2": 15, "pm2_5": 45, "pm10": 80, "nh3": 2},
            "dt": int(datetime.utcnow().timestamp())
        }
    data = r.json()
    item = data["list"][0]
    comps = item["components"]
    
    # Calculate Real AQI
    real_aqi = calculate_ind_aqi(comps["pm2_5"], comps["pm10"])
    
    return {
        "aqi_index": real_aqi, # Now returns 0-500 e.g. 153
        "components": comps,
        "dt": item["dt"],
    }

