@app.get("/fusion", response_model=FusedSensorSnapshot)
async def fuse_signals(
    lat: float = Query(..., ge=-90, le=90),
    lon: float = Query(..., ge=-180, le=180),
):
    """
    Core endpoint for the Sensor Fusion Agent.
    Input: lat, lon.
    Output: fused AQ + weather with derived metrics.
    """
    async with httpx.AsyncClient() as client:
        aq_data, w_data = await asyncio.gather(
            fetch_air_quality(client, lat, lon),
            fetch_weather(client, lat, lon),
        )

    ts = max(aq_data["dt"], w_data["dt"])
    dispersion = compute_dispersion_score(
        aqi_index=aq_data["aqi_index"],
        wind_speed=w_data["wind_speed"],
        clouds=w_data["clouds"],
    )
    health_risk = aqi_to_category(aq_data["aqi_index"])
    
    # Generate Insight
    insight = generate_agent_insight(health_risk, w_data["wind_speed"], aq_data["components"]["pm2_5"], aq_data["components"]["pm10"], aq_data["aqi_index"])

    return FusedSensorSnapshot(
        lat=lat,
        lon=lon,
        timestamp_utc=datetime.fromtimestamp(ts),
        air_quality=AirQuality(
            aqi_index=aq_data["aqi_index"],
            aqi_category=health_risk,
            components=PollutantComponents(**aq_data["components"]),
        ),
        weather=Weather(**{k: v for k, v in w_data.items() if k != "dt"}),
        dispersion_score=dispersion,
        health_risk_level=health_risk,
        agent_insight=insight
    )

@app.get("/search", response_model=FusedSensorSnapshot)
async def search_city(q: str = Query(..., min_length=1)):
    """
    Search for a city, geocode it, and return fused environmental data.
    Uses JSON cache for faster retrieval.
    """
    
    # 1. Check Cache
    try:
        if os.path.exists(LOG_FILE):
             async with aiofiles.open(LOG_FILE, mode='r') as f:
                content = await f.read()
                try:
                    logs = json.loads(content)
                    # Find a valid search_result for this query or location
                    cached = next((item for item in logs if item.get("type") == "search_result" and (item.get("query", "").lower() == q.lower() or item.get("location", "").lower() == q.lower())), None)
                    
                    if cached:
                        print(f"Cache hit for {q}")
                        # Return cached data if structurally valid, else continue to fetch
                        # This is a simple cache; in prod, check timestamp for freshness
                        try:
                            return FusedSensorSnapshot(**cached["data"])
                        except:
                            pass # Invalid structure, re-fetch
                except json.JSONDecodeError:
                    pass
    except Exception as e:
        print(f"Cache check error: {e}")

    async with httpx.AsyncClient() as client:
        # 1. Geocode
        coords = await fetch_coordinates(client, q)
        lat, lon = coords["lat"], coords["lon"]
        
        # 2. Fuse Signals (Reusing logic)
        aq_data, w_data = await asyncio.gather(
            fetch_air_quality(client, lat, lon),
            fetch_weather(client, lat, lon),
        )

        # 3. Fetch AccuWeather for Forecast & RealFeel
        import accuweather_client
        accu_data = await accuweather_client.fetch_accuweather_data(client, coords["name"])

    ts = max(aq_data["dt"], w_data["dt"])
    dispersion = compute_dispersion_score(
        aqi_index=aq_data["aqi_index"],
        wind_speed=w_data["wind_speed"],
        clouds=w_data["clouds"],
    )
    health_risk = aqi_to_category(aq_data["aqi_index"])
    
    insight = generate_agent_insight(health_risk, w_data["wind_speed"], aq_data["components"]["pm2_5"], aq_data["components"]["pm10"], aq_data["aqi_index"])

    # Enhance Weather with RealFeel if available
    weather_obj = Weather(**{k: v for k, v in w_data.items() if k != "dt"})
    if accu_data and accu_data.get("current"):
        rf = accu_data["current"].get("RealFeelTemperature", {}).get("Metric", {}).get("Value")
        if rf:
            # Append RealFeel to description or similar if strictly adhering to model, 
            # or ideally add a field to Weather model. For now, we append to condition text.
            weather_obj.description += f" (RealFeel: {rf}°C)"

    # Construct Forecast
    forecast_list = []
    if accu_data and accu_data.get("forecast"):
        daily = accu_data["forecast"].get("DailyForecasts", [])
        for day in daily[:3]:
            forecast_list.append({
                "date": day["Date"],
                "min_temp": day["Temperature"]["Minimum"]["Value"],
                "max_temp": day["Temperature"]["Maximum"]["Value"], 
                "avg_temp": (day["Temperature"]["Minimum"]["Value"] + day["Temperature"]["Maximum"]["Value"]) / 2, # Approx
                "condition": day["Day"]["IconPhrase"]
            })

    result = FusedSensorSnapshot(
        lat=lat,
        lon=lon,
        timestamp_utc=datetime.fromtimestamp(ts),
        air_quality=AirQuality(
            aqi_index=aq_data["aqi_index"],
            aqi_category=health_risk,
            components=PollutantComponents(**aq_data["components"]),
        ),
        weather=weather_obj,
        dispersion_score=dispersion,
        health_risk_level=health_risk,
        agent_insight=f"Search Result for {coords['name']}: {insight}",
        data={"forecast_3day": forecast_list} # Inject forecast into generic data dict
    )

    # Log to Cache
    await save_to_json_cache({
        "type": "search_result",
        "query": q,
        "location": coords["name"],
        "data": json.loads(result.json())
    })
    
    return result

@app.get("/ask", response_model=AskResponse)
async def ask_agent(q: str = Query(..., min_length=1)):
    if not os.getenv("GROQ_API_KEY"):
        raise HTTPException(status_code=503, detail="Groq AI not configured")

    from groq import Groq
    client_groq = Groq(api_key=os.getenv("GROQ_API_KEY"))

    async with httpx.AsyncClient() as client:
        # 1. Intent Classification & Entity Extraction via Groq
        try:
             # Enhanced prompt for indirect location references
            prompt1 = f"""
            Analyze this query: "{q}"
            1. Identify if the user is asking about a location (even indirectly like "Capital of India").
            2. If yes, resolve the specific City Name.
            3. Determine the intent: "weather", "aqi", "general".
            
            Output JSON only: {{"city": "ResolvedCityName" or null, "intent": "string"}}
            """
            
            completion = client_groq.chat.completions.create(
                messages=[{"role": "user", "content": prompt1}],
                model="llama-3.3-70b-versatile",
                temperature=0,
                response_format={"type": "json_object"}
            )
            resp1_text = completion.choices[0].message.content
            print(f"Groq Intent Response: {resp1_text}")
            
        except Exception as e:
            print(f"Groq Intent/Setup Error: {e}")
            raise HTTPException(status_code=500, detail=f"AI Error: {e}")

        city = None
        intent = "general"
        try:
            parsed = json.loads(resp1_text)
            city = parsed.get("city")
            intent = parsed.get("intent", "general")
        except Exception as e:
            print(f"Failed to parse Groq intention: {resp1_text}, Error: {e}")

        data_context = {}
        location_info = None

        # 2. Fetch Data if City Found
        if city:
            try:
                coords = await fetch_coordinates(client, city)
                lat, lon = coords["lat"], coords["lon"]
                location_info = {"lat": lat, "lon": lon, "name": coords["name"]}
                
                # Fetch basic OpenWeather Data
                aq_data, w_data = await asyncio.gather(
                    fetch_air_quality(client, lat, lon),
                    fetch_weather(client, lat, lon),
                )
                
                # Fetch Detailed AccuWeather Forecast
                import accuweather_client
                accu_data = await accuweather_client.fetch_accuweather_data(client, coords["name"])
                
                # Retrieve forecast for immediate display (Today, Tomorrow, DayAfter)
                forecast_summary = []
                if accu_data and accu_data.get("forecast"):
                    daily = accu_data["forecast"].get("DailyForecasts", [])
                    for day in daily[:3]:
                        forecast_summary.append({
                            "date": day["Date"],
                            "min_temp": day["Temperature"]["Minimum"]["Value"],
                            "max_temp": day["Temperature"]["Maximum"]["Value"],
                            "unit": day["Temperature"]["Maximum"]["Unit"],
                            "phrase": day["Day"]["IconPhrase"]
                        })

                data_context = {
                    "location": coords["name"],
                    "current": {
                        "temp": w_data["temperature_c"],
                        "aqi": aq_data["aqi_index"],
                        "pm25": aq_data["components"]["pm2_5"],
                        "wind": w_data["wind_speed"],
                        "insight": generate_agent_insight(aqi_to_category(aq_data["aqi_index"]), w_data["wind_speed"], aq_data["components"]["pm2_5"], aq_data["components"]["pm10"], aq_data["aqi_index"])
                    },
                    "forecast_3day": forecast_summary
                }
            except Exception as e:
                print(f"Data fetch error: {e}")

        # 3. Generate Answer
        prompt2 = f"""
        User Query: "{q}"
        Resolved City: {city}
        Context Data: {json.dumps(data_context)}
        
        Task:
        1. Answer the user's question naturally.
        2. If data is present, explicitly mention the current AQI, Temperature, and the 3-day forecast trend.
        3. If the query was about "Capital of X", confirm the city name in the answer.
        4. Be concise and helpful.
        """
        try:
            completion2 = client_groq.chat.completions.create(
                messages=[{"role": "user", "content": prompt2}],
                model="llama-3.3-70b-versatile",
                temperature=0.5
            )
            final_answer = completion2.choices[0].message.content
        except Exception as e:
            print(f"Groq Answer Gen Error: {e}")
            final_answer = "I'm sorry, I couldn't generate a response at this time."
        
        if city:
            # Log successful ask
            await save_to_json_cache({
                "type": "ask_interaction",
                "query": q,
                "city_resolved": city,
                "intent": intent, 
                "response": final_answer
            })
            
        return AskResponse(
            answer=final_answer,
            location=location_info,
            data=data_context
        )

